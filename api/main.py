# REQUEST SCHEMA

class TransactionRequest(BaseModel):
    """
    Validated real-time transaction request.

    TransactionID is optional and will be generated by the
    transaction input module when omitted.

    isFraud is intentionally not part of this schema because
    the prediction API must not accept the ground-truth label.
    """

    model_config = ConfigDict(
        extra="forbid"
    )

    TransactionID: Optional[str] = Field(
        default=None,
        min_length=1,
        max_length=128,
        description=(
            "Optional transaction identifier. "
            "Generated automatically when omitted."
        ),
    )

    TransactionDT: float = Field(
        ...,
        description="Transaction timestamp.",
    )

    TransactionAmt: float = Field(
        ...,
        ge=0.0,
        description="Transaction amount.",
    )

    ProductCD: Optional[str] = Field(
        default=None,
        min_length=1,
        description="IEEE-CIS product category.",
    )

    card1: Optional[float] = None
    card2: Optional[float] = None
    card3: Optional[float] = None
    card5: Optional[float] = None

    addr1: Optional[float] = None
    addr2: Optional[float] = None

    P_emaildomain: Optional[str] = None
    R_emaildomain: Optional[str] = None

    DeviceInfo: Optional[str] = None

    # TRANSACTION ID VALIDATION

    @field_validator("TransactionID")
    @classmethod
    def validate_transaction_id(
        cls,
        value: Optional[str],
    ) -> Optional[str]:

        if value is None:
            return None

        value = value.strip()

        if not value:
            raise ValueError(
                "TransactionID cannot be empty."
            )

        return value

    # TIMESTAMP VALIDATION

    @field_validator("TransactionDT")
    @classmethod
    def validate_transaction_dt(
        cls,
        value: float,
    ) -> float:

        if not math.isfinite(value):
            raise ValueError(
                "TransactionDT must be a finite number."
            )

        if value < 0:
            raise ValueError(
                "TransactionDT cannot be negative."
            )

        return float(value)

    # AMOUNT VALIDATION

    @field_validator("TransactionAmt")
    @classmethod
    def validate_transaction_amount(
        cls,
        value: float,
    ) -> float:

        if not math.isfinite(value):
            raise ValueError(
                "TransactionAmt must be a finite number."
            )

        if value < 0:
            raise ValueError(
                "TransactionAmt cannot be negative."
            )

        return float(value)

    # PRODUCT VALIDATION

    @field_validator("ProductCD")
    @classmethod
    def validate_product(
        cls,
        value: Optional[str],
    ) -> Optional[str]:

        if value is None:
            return None

        value = value.strip()

        if not value:
            raise ValueError(
                "ProductCD cannot be empty."
            )

        return value

    # STRING FIELD CLEANING

    @field_validator(
        "P_emaildomain",
        "R_emaildomain",
        "DeviceInfo",
    )
    @classmethod
    def clean_string_fields(
        cls,
        value: Optional[str],
    ) -> Optional[str]:

        if value is None:
            return None

        value = value.strip()

        if not value:
            return None

        return value

    # NUMERIC FIELD VALIDATION

    @field_validator(
        "card1",
        "card2",
        "card3",
        "card5",
        "addr1",
        "addr2",
    )
    @classmethod
    def validate_optional_numeric(
        cls,
        value: Optional[float],
    ) -> Optional[float]:

        if value is None:
            return None

        if not math.isfinite(value):
            raise ValueError(
                "Numeric transaction fields must "
                "contain finite values."
            )

        return float(value)


