@app.post("/predict")
def predict(
    request: TransactionRequest,
) -> Dict[str, Any]:

    if pipeline is None:

        raise HTTPException(
            status_code=503,
            detail={
                "status": "error",
                "message": (
                    "RFGN inference service "
                    "is not ready."
                ),
            },
        )

    try:

        transaction_data = request.model_dump(
            exclude_none=True
        )

        transaction_id = transaction_data.pop(
            "TransactionID",
            None,
        )

        result = pipeline.process_transaction(
            transaction_data=transaction_data,
            transaction_id=transaction_id,
            store_result=True,
        )

        return {

            "status": "success",

            "transaction_id": result[
                "transaction_id"
            ],

            "fraud_probability": result[
                "graphsage"
            ][
                "fraud_probability"
            ],

            "legitimate_probability": result[
                "graphsage"
            ][
                "legitimate_probability"
            ],

            "dqn_threshold": result[
                "dqn"
            ][
                "selected_threshold"
            ],

            "dqn_action": result[
                "dqn"
            ][
                "action"
            ],

            "decision": result[
                "final_decision"
            ][
                "decision"
            ],

            "predicted_class": result[
                "final_decision"
            ][
                "predicted_class"
            ],

            "model": "Global GraphSAGE + DQN",
        }

    except ValueError as exc:

        raise HTTPException(
            status_code=400,
            detail={
                "status": "error",
                "type": "validation_error",
                "message": str(exc),
            },
        )

    except Exception as exc:

        raise HTTPException(
            status_code=500,
            detail={
                "status": "error",
                "type": "inference_error",
                "message": str(exc),
            },
        )