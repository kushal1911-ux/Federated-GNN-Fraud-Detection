@app.get("/health")
def health() -> Dict[str, Any]:

    if pipeline is None:

        raise HTTPException(
            status_code=503,
            detail={
                "system": "RFGN",
                "status": "initializing",
            },
        )

    try:

        pipeline_health = pipeline.health_check()

        return {
            "system": "RFGN",
            "status": "healthy",
            "pipeline": pipeline_health,
        }

    except Exception as exc:

        raise HTTPException(
            status_code=503,
            detail={
                "system": "RFGN",
                "status": "unhealthy",
                "error": str(exc),
            },
        )


